  await page.locator('#export-confirm').click();
  await page.locator('#contact-search').fill('');
  await page.screenshot({path: path.join(output, 'contacts-light-1320.png')});

  await page.locator('[data-workspace="message"]').click();
  await page.locator('#start-message').click();
  await page.locator('#task-monitor').waitFor({state: 'visible'});
  await page.locator('#pause-task').click();
  const elapsed = await page.locator('#elapsed-time').innerText();
  await page.waitForTimeout(1300);
  assert.equal(await page.locator('#elapsed-time').innerText(), elapsed);
  await page.locator('#open-settings').click();
  await page.locator('[data-settings="friends"]').click();
  assert.ok(await page.locator('#friend-min').isDisabled());
  await page.locator('#settings-done').click();
  await page.locator('#pause-task').click();
  await page.screenshot({path: path.join(output, 'monitor-light-1320.png')});
  await page.locator('#stop-task').click();
  await page.locator('#return-editor').click();
  await page.locator('[data-workspace="friends"]').click();
  await page.locator('#start-friends').click();
  await page.locator('#task-waiting').filter({hasText: '下一条将在'}).waitFor();
  assert.ok((await page.locator('#health-label').innerText()).includes('自动化执行中'));
  await page.locator('#pause-task').click();
  const friendElapsed = await page.locator('#elapsed-time').innerText();
  assert.notEqual(friendElapsed, '00:00:00');
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('#elapsed-time').innerText(), friendElapsed);
  await page.locator('#pause-task').click();
  await page.locator('#task-scenario').click();
  await page.locator('[data-scenario="risk"]').click();
  await page.locator('#return-editor').click();
  assert.equal(await page.locator('#friend-table tr.risk').count(), 1);
  assert.ok((await page.locator('#friend-current').innerText()).includes('频繁限制'));
  const cell = page.locator('#friend-table tbody tr').first().locator('[data-field="name"]');
