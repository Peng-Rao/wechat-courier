  fs.mkdirSync(output, {recursive: true});
  const browser = await chromium.launch({headless: true, channel: 'msedge'});
  const context = await browser.newContext({viewport: {width: 1320, height: 880}});
  const page = await context.newPage();
  await page.emulateMedia({reducedMotion: 'reduce'});
  const errors = [];
  const external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', request => {if (/^https?:/.test(request.url())) external.push(request.url());});
  page.on('requestfailed', request => errors.push(`${request.url()}: ${request.failure()?.errorText}`));
  await context.route(/^https?:/, route => route.abort());
  await page.goto(pathToFileURL(entry).href);
  await page.getByRole('heading', {name: '消息群发', exact: true}).waitFor();
  await page.locator('#sidebar-toggle').click();
  assert.equal(await page.locator('.app').getAttribute('data-sidebar'), 'collapsed');
  await page.locator('#sidebar-toggle').click();
  await page.locator('#recipients').fill('演示同学甲\n演示同学乙\n演示同学丙');
  await page.locator('#message-template').fill('{name}，你好。');
