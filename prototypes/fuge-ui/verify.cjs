  await page.screenshot({path: path.join(output, 'message-light-1320.png')});

  await page.locator('[data-workspace="friends"]').click();
  assert.equal(await page.locator('#friend-table tbody tr').count(), 200);
  assert.ok((await page.locator('#friend-selection-count').innerText()).includes('0 / 100'));
  await page.locator('#range-end').fill('5');
  await page.locator('#select-range').click();
  assert.equal(await page.locator('#friend-table tbody input[type=checkbox]:checked').count(), 5);
  await page.locator('#friend-table tbody tr').nth(7).click();
  assert.equal(await page.locator('#friend-table tbody input[type=checkbox]:checked').count(), 5);
  const editable = page.locator('#friend-table tbody tr').first().locator('[data-field="name"]');
  await editable.dblclick();
  await editable.locator('input').fill('新演示姓名');
  await page.keyboard.press('Enter');
  assert.ok((await editable.innerText()).includes('新演示姓名'));
  await page.locator('#range-end').fill('200');
  await page.locator('#select-range').click();
  assert.equal(await page.locator('#friend-table tbody input[type=checkbox]:checked').count(), 5);
  await page.screenshot({path: path.join(output, 'friends-light-1320.png')});

  await page.locator('#open-settings').click();
  await page.locator('[data-settings="friends"]').click();
  await page.locator('#friend-min').fill('30');
  await page.locator('#friend-min').press('Enter');
  assert.equal(await page.locator('#friend-max').inputValue(), '30');
  await page.locator('#friend-max').fill('40');
  await page.locator('#settings-done').click();
  await page.locator('#open-settings').click();
  assert.equal(await page.locator('#friend-min').inputValue(), '30');
  assert.equal(await page.locator('#friend-max').inputValue(), '40');
  await page.locator('#friend-max').fill('41');
  await page.keyboard.press('Escape');
  await page.locator('#open-settings').click();
  assert.equal(await page.locator('#friend-max').inputValue(), '41', 'Escape must save the currently focused interval input');
  await page.locator('#friend-max').fill('40');
  await page.locator('#friend-max').press('Enter');
  await page.locator('#default-greeting').click({button: 'right'});
  await page.locator('#context-menu').waitFor({state: 'visible'});
  assert.ok(await page.locator('#context-menu').evaluate(menu => {
    const r = menu.getBoundingClientRect();
    return menu.contains(document.elementFromPoint(r.x + 20, r.y + 20));
  }), 'context menu must be above a modal dialog');
  await page.keyboard.press('Escape');
  if (!(await page.locator('#settings-dialog').isVisible())) await page.locator('#open-settings').click();
  await page.waitForTimeout(180);
  await page.screenshot({path: path.join(output, 'settings-light-1320.png')});
  await page.locator('#settings-done').click();

  await page.locator('[data-workspace="contacts"]').click();
  await page.locator('#contact-search').fill('设计');
  assert.ok(await page.locator('#contact-table tbody tr[data-contact]').count() > 0);
  await page.locator('#export-contacts').click();
